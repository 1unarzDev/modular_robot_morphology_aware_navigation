"""Macros: the mechanism counts the interpretation rules require, per record.

The interpretation rules (statistical analysis plan, declared 2026-11-04 before
any confirmatory outcome was read) allow a control to be said to fail "for the
reason it does not model" only when those records' earliest cause is that
mechanism, and require every exception to be given:

- `geometry_coupled` in the reconfiguration-workspace family: contact;
- `feasibility_coupled` in the two sensing families: refused docking at a site
  the station cannot see.

`make_failure_table.py` counts terminal statuses, which already name the
earliest evaluator cause, but cannot tell whether a refusal happened at a site
the station cannot see. This recomputes that per record with
`evaluator_metrics.station_observability_audit`, given no recorded alignment so
that its only possible finding is the planner's prediction of a blind site, at
the transition sites the mission actually planned. It lists every failure in
scope that is not the named mechanism. It decides nothing and excludes
nothing; neutral controls (every fourth layout) are out of scope, as in the
failure table. Written, and its definitions fixed, before unblinding.

    python3 paper/conference/make_mechanism_table.py <raw-record-dir> \
        <design.json> paper/conference/mechanism_macros.tex [mechanism.json]

Needs `morphology_planner` and `modular_robot_benchmarks` importable, so it
runs in the container, from the workspace root (for the catalog path).
"""
from __future__ import annotations

import json
import sys
from pathlib import Path
from types import SimpleNamespace

CATALOG = Path("src/modular_robot_description/config/morphologies.yaml")
DOCKING_REFUSED = ("docking_failure", "unsafe_topology")
# (macro key, method, families, what counts as the mechanism)
SCOPES = (
    ("Geom", "geometry_coupled", ("reconfiguration_workspace",), "contact"),
    ("Feas", "feasibility_coupled",
     ("docking_observability", "combined_constraints"), "blind_refusal"),
)
FAMILY_NAMES = {"reconfiguration_workspace": "workspace",
                "docking_observability": "docking",
                "combined_constraints": "combined"}


def _neutral(layout_id: str) -> bool:
    return int(layout_id.rsplit("-", 1)[1]) % 4 == 0


def classify(record: dict, mechanism: str, blind) -> str:
    """'mechanism', or the reason this failure is an exception.

    `blind(record)` is True when a planned site is one the station cannot see,
    False when the station is predicted to see every planned site, and None
    when the record planned no transition site.
    """
    status = record["terminal_status"]
    if mechanism == "contact":
        return "mechanism" if status == "collision" else status
    if status not in DOCKING_REFUSED:
        return status
    verdict = blind(record)
    if verdict is None:
        return f"{status} with no planned transition site"
    return "mechanism" if verdict else f"{status} at a site the station is predicted to see"


def tabulate(raw: Path, blind) -> dict:
    scopes = {key: {"method": method, "families": list(families),
                    "mechanism": mechanism, "trials": 0, "failures": 0,
                    "mechanism_count": 0, "exceptions": []}
              for key, method, families, mechanism in SCOPES}
    for path in sorted(Path(raw).glob("*.json")):
        with path.open(encoding="utf-8") as stream:
            record = json.load(stream)
        spec = record["spec"]
        if _neutral(spec["layout_id"]):
            continue
        for key, method, families, mechanism in SCOPES:
            if spec["method"] != method or spec["family"] not in families:
                continue
            scope = scopes[key]
            scope["trials"] += 1
            if record["terminal_status"] == "completed":
                continue
            scope["failures"] += 1
            verdict = classify(record, mechanism, blind)
            if verdict == "mechanism":
                scope["mechanism_count"] += 1
            else:
                scope["exceptions"].append({
                    "layout_id": spec["layout_id"], "replicate": spec["replicate"],
                    "terminal_status": record["terminal_status"], "reason": verdict})
    return scopes


def _exception_list(exceptions: list[dict]) -> str:
    if not exceptions:
        return "none"
    items = []
    for value in exceptions:
        family, index = value["layout_id"].rsplit("-", 1)
        reason = value["reason"].replace("_", " ")
        items.append(f"{FAMILY_NAMES.get(family, family)} layout {int(index)} "
                     f"replicate {value['replicate']}: {reason}")
    return "; ".join(items)


def render(scopes: dict) -> str:
    lines = ["% Generated by make_mechanism_table.py from the raw terminal records; "
             "do not edit by hand."]
    for key, scope in scopes.items():
        for name, value in (("Trials", scope["trials"]),
                            ("Failures", scope["failures"]),
                            ("Count", scope["mechanism_count"]),
                            ("Exceptions", len(scope["exceptions"])),
                            ("ExceptionList", _exception_list(scope["exceptions"]))):
            lines.append(rf"\newcommand{{\resMech{key}{name}}}{{{value}}}")
    return "\n".join(lines) + "\n"


def station_blindness(design_path: Path, catalog_path: Path = CATALOG):
    """`blind(record)` from the planner's station prediction at the planned sites."""
    from modular_robot_benchmarks.confirmatory_scenarios import make_confirmatory_scenario
    from modular_robot_benchmarks.design import StudyDesign, layout_generator_for
    from modular_robot_benchmarks.evaluator_metrics import station_observability_audit
    from morphology_planner import load_catalog

    generator = layout_generator_for(StudyDesign.read_frozen(design_path).design_kind)
    catalog = load_catalog(str(catalog_path)).supported_experiment_subset()
    scenarios: dict = {}

    def blind(record: dict) -> bool | None:
        sites = record.get("planned_transition_sites") or []
        if not sites:
            return None
        spec = record["spec"]
        layout = spec["layout_id"]
        if layout not in scenarios:
            scenarios[layout] = make_confirmatory_scenario(
                spec["family"], int(layout.rsplit("-", 1)[1]), int(spec["world_seed"]),
                generator=generator)
        scenario = scenarios[layout]
        if not scenario.fiducial_stations:
            raise ValueError(f"{layout} declares no station")
        problems = station_observability_audit(
            SimpleNamespace(planned_transition_sites=sites, pod_alignment_history=[]),
            scenario, catalog)
        return bool(problems)

    return blind


def main() -> None:
    scopes = tabulate(Path(sys.argv[1]), station_blindness(Path(sys.argv[2])))
    Path(sys.argv[3]).write_text(render(scopes), encoding="utf-8")
    if len(sys.argv) > 4:
        Path(sys.argv[4]).write_text(json.dumps(scopes, indent=2, sort_keys=True) + "\n",
                                     encoding="utf-8")


if __name__ == "__main__":
    main()
